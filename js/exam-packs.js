/**
 * Competitive-exam practice packs.
 *
 * Students here sit JEE, NEET and AP EAPCET as well as school exams, and every
 * one of those has a *shape*: a number of questions, a time per question, and a
 * reward for being right or wrong. Practising in the wrong shape teaches the
 * wrong instinct - answering a 300-mark paper with negative marking like it is
 * a one-mark school test is how good students lose marks.
 *
 * So this module holds the shape of each exam, and nothing else. It ships no
 * questions and no prep material: the questions come from the pages the student
 * has, generated by the same cited engine as everything else. That is
 * deliberate - coaching PDFs and previous-year papers belong to their
 * publishers, and this project must not become a copy of them.
 *
 * What is stored here is the *pattern*: counts, timing and marking, which are
 * facts published by the official bodies, plus a chapter outline. Every pack
 * carries the official link and a "check the official syllabus" line, because
 * patterns change and a school project should never be anyone's only source.
 *
 * Pure functions only: no DOM, no imports, no network. Everything works offline.
 */

